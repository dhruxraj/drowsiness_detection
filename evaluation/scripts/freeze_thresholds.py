#!/usr/bin/env python3
"""Freeze the detection thresholds in config.yaml before the final evaluation.

Run this once, AFTER tuning on the tuning split and BEFORE looking at any final-split
result:

    python evaluation/scripts/freeze_thresholds.py \
        --selection-method "grid search, evaluation/results/runs/<tuning_run>/tuning/tuning_results.csv" \
        --tuning-run evaluation/results/runs/<tuning_run>

If you decide to evaluate the current defaults without tuning, say so explicitly:

    python evaluation/scripts/freeze_thresholds.py --untuned-defaults \
        --selection-method "config.yaml design defaults, not tuned on data"
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from evaluation.core import eval_config, thresholds as th, workflow  # noqa: E402
from evaluation.core.dataset import DatasetError  # noqa: E402
from evaluation.core.pipeline import read_config_dict  # noqa: E402
from evaluation.core.provenance import git_info, sha256_file, utc_now  # noqa: E402
from evaluation.core.splits import assert_separated, load_split  # noqa: E402

HEADER = """\
# FROZEN DETECTION THRESHOLDS - generated by evaluation/scripts/freeze_thresholds.py
# Do not edit by hand. evaluate.py --split final refuses to run if config.yaml or the
# evaluation protocol no longer match the fingerprints below.
"""


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--config", default=str(eval_config.DEFAULT_EVAL_CONFIG))
    p.add_argument("--system-config")
    p.add_argument("--selection-method", required=True, help="how the thresholds were chosen (recorded verbatim)")
    p.add_argument("--tuning-run", help="tuning run directory the selection was based on")
    p.add_argument("--notes", default="")
    p.add_argument("--untuned-defaults", action="store_true",
                   help="allow freezing without any tuning recordings (documented as untuned)")
    p.add_argument("--force", action="store_true", help="overwrite an existing frozen file")
    args = p.parse_args(argv)

    cfg = eval_config.load(args.config)
    sys_cfg_path = Path(args.system_config) if args.system_config else eval_config.resolve(cfg["paths"]["system_config"])
    out = eval_config.resolve(cfg["paths"]["frozen_thresholds"])
    try:
        tuning = load_split(cfg, "tuning")
        final = load_split(cfg, "final", with_labels=False)
        assert_separated(tuning, final)
    except DatasetError as exc:
        print("DATASET ERROR - not frozen:\n  " + "\n  ".join(exc.errors))
        return 2
    if not tuning.recordings and not args.untuned_defaults:
        print("The tuning split is empty. Tune on real tuning recordings first, or pass "
              "--untuned-defaults to freeze the current values as explicitly untuned defaults.")
        return 1
    existing = workflow.load_frozen(out)
    if existing and existing.get("status") == th.FROZEN and not args.force:
        print(f"{out} is already frozen. Re-freezing after final results have been seen invalidates "
              "the final evaluation; use --force only if no final result has been looked at.")
        return 1
    final_results_existed = (eval_config.resolve(cfg["paths"]["results_dir"]) / "summary.json").is_file()
    if final_results_existed:
        print("WARNING: evaluation/results/summary.json exists - final results were produced before "
              "this freeze. This is recorded in the frozen file.")

    system_cfg = read_config_dict(sys_cfg_path)
    record = th.build_frozen_record(
        system_cfg, cfg,
        tuning_recording_ids=[r.recording_id for r in tuning.recordings],
        tuning_subject_ids=[r.subject_id for r in tuning.recordings],
        tuning_manifest_sha256=sha256_file(tuning.recordings_path) if tuning.recordings_path.is_file() else None,
        selection_method=args.selection_method + (" [UNTUNED DEFAULTS]" if args.untuned_defaults else ""),
        tuning_run=args.tuning_run, git_commit=git_info().get("commit"), frozen_at=utc_now(),
        notes=args.notes, final_results_existed=final_results_existed)
    import yaml
    out.write_text(HEADER + yaml.safe_dump(record, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"Frozen thresholds written to {out}")
    print(f"  detection fingerprint {record['detection_fingerprint'][:16]}, "
          f"{len(record['tuning_recordings'])} tuning recordings, {len(record['tuning_subjects'])} subjects")
    print("Commit this file together with config.yaml before running the final evaluation.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
